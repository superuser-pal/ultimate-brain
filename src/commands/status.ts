import { readdir, readFile } from "node:fs/promises";
import { join } from "node:path";

import type { Command } from "../lib/command.ts";
import { BrainError } from "../lib/errors.ts";
import { buildIndex } from "../lib/index-builder.ts";
import { lintBrain } from "../lib/lint.ts";
import { scanNotes } from "../lib/notes.ts";
import { describeErrors, loadSchemas } from "../lib/schemas.ts";

const NOTE_TYPES = ["area", "project", "person", "org", "meeting", "decision", "question", "concept", "source", "view", "goal", "memory"];
const PROPOSAL_STATUSES = ["pending", "approved", "edited", "rejected", "applied", "closed"];

/** `brain status` (spec/cli.md §5.2). */
export const statusCommand: Command = {
  name: "status",
  usage: "brain status [--json]",
  summary: "Show a read-only health summary for this brain.",
  options: {},
  maxPositionals: 0,
  needsBrain: true,
  async run({ brain }) {
    const schemas = loadSchemas();
    if (!schemas.brain(brain!.config)) {
      throw new BrainError("BRAIN_CONFIG_INVALID", `brain.json fails schema: ${describeErrors(schemas.brain.errors).join("; ")}`);
    }

    const { notes, problems } = await scanNotes(brain!.root);
    const noteCounts = Object.fromEntries(NOTE_TYPES.map((type) => [type, 0])) as Record<string, number>;
    const proposalCounts = Object.fromEntries(PROPOSAL_STATUSES.map((status) => [status, 0])) as Record<string, number>;
    for (const note of notes) {
      if (note.type === "proposal") {
        const status = note.attributes.status;
        if (typeof status === "string" && status in proposalCounts) proposalCounts[status] += 1;
      } else if (note.type in noteCounts) {
        noteCounts[note.type] += 1;
      }
    }

    const index = buildIndex(notes).markdown;
    let currentIndex: string | null = null;
    try {
      currentIndex = await readFile(join(brain!.root, "index.md"), "utf8");
    } catch {
      // A missing index is stale, as it would be regenerated by `brain index`.
    }
    const issues = lintBrain({
      root: brain!.root,
      notes,
      problems,
      brainConfig: brain!.config,
      indexMarkdown: currentIndex,
    });
    const viewStale = issues.filter((issue) => issue.rule === "view-stale").map((issue) => issue.path);

    const notion = readNotion(brain!.config);
    const lastLog = await findLastLogLine(brain!.root);
    const data = {
      schema_version: brain!.config.schema_version,
      owner: (brain!.config.owner as Record<string, unknown>).name,
      notes: noteCounts,
      proposals: proposalCounts,
      notion,
      index_stale: currentIndex !== index,
      views_stale: viewStale,
      last_log: lastLog,
    };
    return { data, human: `Owner: ${data.owner}\nNotes: ${notes.length}\n` };
  },
};

function readNotion(config: Record<string, unknown>): { configured: string[]; missing: string[]; tasks_database: boolean } {
  const notion = config.notion as Record<string, unknown>;
  const databases = notion.databases as Record<string, unknown>;
  const configured: string[] = [];
  const missing: string[] = [];
  for (const [key, value] of Object.entries(databases)) {
    (typeof value === "string" && value !== "" ? configured : missing).push(key);
  }
  const tasks = notion.tasks as Record<string, unknown>;
  return { configured, missing, tasks_database: typeof tasks.database === "string" && tasks.database !== "" };
}

async function findLastLogLine(root: string): Promise<string | null> {
  let entries: string[];
  try {
    entries = (await readdir(join(root, "log"))).filter((entry) => /^\d{4}-\d{2}\.md$/.test(entry)).sort();
  } catch {
    return null;
  }
  for (const entry of entries.reverse()) {
    try {
      const lines = (await readFile(join(root, "log", entry), "utf8")).trimEnd().split("\n");
      for (const line of lines.reverse()) if (line.startsWith("- ")) return line;
    } catch {
      // Status is diagnostic; an unreadable old log does not make the brain unusable.
    }
  }
  return null;
}
