import { compareCodePoints, type Note } from "./notes.ts";

export const INDEX_HEADER = "<!-- GENERATED by brain index. Do not edit. -->";

/** index.md sections, in order (spec/schema.md §13). */
const SECTIONS: ReadonlyArray<readonly [type: string, heading: string]> = [
  ["area", "Areas"],
  ["goal", "Goals"],
  ["project", "Projects"],
  ["person", "People"],
  ["org", "Orgs"],
  ["decision", "Decisions"],
  ["question", "Questions"],
  ["meeting", "Meetings"],
  ["concept", "Concepts"],
  ["reference", "References"],
];

const NON_KNOWLEDGE = new Set(["source", "view", "proposal"]);
const TYPES = [...SECTIONS.map(([type]) => type), "source", "view", "proposal", "memory"];

/** Computed inverses exposed as backlinks (spec/schema.md §6). */
const RELATION_INVERSES: Readonly<Record<string, string>> = {
  about: "mentioned_in",
  depends_on: "needed_by",
  contradicts: "contradicts",
  derived_from: "used_by",
  related_to: "related_to",
};
const FIELD_INVERSES: ReadonlyArray<readonly [field: string, inverse: string]> = [
  ["projects", "project_of"],
  ["area", "area_of"],
  ["goal", "goal_of"],
  ["client", "client_of"],
  ["org", "member"],
  ["attendees", "attended"],
  ["decided_in", "decisions"],
  ["raised_in", "questions"],
];

export interface IndexEntry {
  id: string;
  type: string;
  title: string | null;
  path: string;
  summary: string | null;
  lifecycle: string | null;
  aliases: unknown[];
  tags: unknown[];
  area: string | null;
  projects: unknown[];
  updated: string | null;
  notion: string | null;
  fields: Record<string, unknown>;
}

export interface Backlink {
  type: string;
  source: string;
}

export interface BuiltIndex {
  markdown: string;
  entries: IndexEntry[];
  backlinks: Record<string, Backlink[]>;
  counts: Record<string, number>;
  duplicates: Array<{ id: string; path: string; kept: string }>;
}

/** Build index.md and the agent-facing index from notes sorted by path. */
export function buildIndex(allNotes: readonly Note[]): BuiltIndex {
  const byId = new Map<string, Note>();
  const duplicates: BuiltIndex["duplicates"] = [];
  const notes: Note[] = [];
  for (const note of allNotes) {
    const kept = byId.get(note.id);
    if (kept !== undefined) {
      duplicates.push({ id: note.id, path: note.path, kept: kept.path });
      continue;
    }
    byId.set(note.id, note);
    notes.push(note);
  }

  // Every type has a count, zero included (spec/cli.md §5.8).
  const counts: Record<string, number> = Object.fromEntries(TYPES.map((type) => [type, 0]));
  for (const note of notes) counts[note.type] = (counts[note.type] ?? 0) + 1;

  return {
    markdown: renderMarkdown(notes, byId),
    entries: notes.map(toEntry),
    backlinks: computeBacklinks(notes, byId),
    counts,
    duplicates,
  };
}

function renderMarkdown(notes: readonly Note[], byId: ReadonlyMap<string, Note>): string {
  const lines = [INDEX_HEADER, "", "# Index"];
  for (const [type, heading] of SECTIONS) {
    const section = notes
      .filter((note) => note.type === type)
      .sort((a, b) => compareCodePoints(sortKey(a), sortKey(b)) || compareCodePoints(a.id, b.id));
    if (section.length === 0) continue;
    lines.push("", `## ${heading}`, ...section.map((note) => renderLine(note, byId)));
  }
  return `${lines.join("\n")}\n`;
}

function sortKey(note: Note): string {
  return text(note.attributes.title).normalize("NFC").toLowerCase();
}

function renderLine(note: Note, byId: ReadonlyMap<string, Note>): string {
  const a = note.attributes;
  const title = oneLine(text(a.title)).replaceAll("\\", "\\\\").replaceAll("[", "\\[").replaceAll("]", "\\]");
  const segments = [`- [${title}](${note.path}) — ${note.id}`];

  for (const [label, value] of typeFields(note, byId)) {
    if (value !== undefined && value !== "") segments.push(`${label}: ${oneLine(value)}`);
  }
  if (typeof a.summary === "string") segments.push(oneLine(a.summary));
  const aliases = list(a.aliases).filter(isScalar).map((alias) => oneLine(String(alias)));
  if (aliases.length > 0) segments.push(`aliases: ${aliases.join(", ")}`);
  if (a.lifecycle === "disputed" || a.lifecycle === "archived") segments.push(String(a.lifecycle));

  return segments.join(" · ");
}

/** Per-type index fields, rendered (references as titles). */
function typeFields(note: Note, byId: ReadonlyMap<string, Note>): Array<[string, string | undefined]> {
  const a = note.attributes;
  const ref = (value: unknown) => (typeof value === "string" ? titleOf(value, byId) : undefined);
  const refs = (value: unknown) => {
    const items = list(value).filter((item): item is string => typeof item === "string").map((item) => titleOf(item, byId));
    return items.length === 0 ? undefined : items.join(", ");
  };
  const scalar = (value: unknown) => (isScalar(value) ? String(value) : undefined);
  const notionField = (key: string) => scalar(record(a.notion_fields)[key]);
  const fact = (key: string) => scalar(record(a.facts)[key]);

  switch (note.type) {
    case "goal":
      return [["area", ref(a.area)], ["status", notionField("status")], ["deadline", fact("deadline")]];
    case "project":
      return [["area", ref(a.area)], ["status", notionField("status")], ["client", ref(a.client)]];
    case "person":
      return [["org", ref(a.org)], ["role", fact("role")]];
    case "org":
      return [["relationship", notionField("relationship")]];
    case "decision":
      return [["date", scalar(a.date)], ["assessment", scalar(a.assessment)], ["project", refs(a.projects)]];
    case "question":
      return [["kind", scalar(a.kind)], ["status", notionField("status")]];
    case "meeting":
      return [["date", scalar(a.date)], ["project", refs(a.projects)]];
    case "reference":
      return [["area", ref(a.area)], ["project", refs(a.projects)]];
    default:
      return [];
  }
}

function toEntry(note: Note): IndexEntry {
  const a = note.attributes;
  const nullable = (value: unknown) => (value === undefined ? null : value);
  return {
    id: note.id,
    type: note.type,
    title: nullable(a.title) as string | null,
    path: note.path,
    summary: nullable(a.summary) as string | null,
    lifecycle: NON_KNOWLEDGE.has(note.type) ? null : (nullable(a.lifecycle) as string | null),
    aliases: list(a.aliases),
    tags: list(a.tags),
    area: nullable(a.area) as string | null,
    projects: list(a.projects),
    updated: nullable(a.updated) as string | null,
    notion: nullable(a.notion) as string | null,
    fields: entryFields(note),
  };
}

/** Raw (unrendered) per-type fields for the JSON index (spec/cli.md §5.8). */
function entryFields(note: Note): Record<string, unknown> {
  const a = note.attributes;
  const notionFields = record(a.notion_fields);
  const facts = record(a.facts);
  const picks: Record<string, Array<[string, unknown]>> = {
    goal: [["status", notionFields.status], ["deadline", facts.deadline]],
    project: [["status", notionFields.status], ["client", a.client], ["goal", a.goal]],
    person: [["org", a.org], ["role", facts.role]],
    org: [["relationship", notionFields.relationship]],
    decision: [["date", a.date], ["assessment", a.assessment]],
    question: [["kind", a.kind], ["status", notionFields.status]],
    meeting: [["date", a.date]],
    source: [["source_key", a.source_key]],
    view: [["view_kind", a.view_kind], ["project", a.project]],
    proposal: [["kind", a.kind], ["status", a.status], ["target", a.target]],
    memory: [["scope", a.scope]],
  };
  const fields: Record<string, unknown> = {};
  for (const [key, value] of picks[note.type] ?? []) {
    if (value !== undefined && value !== null) fields[key] = value;
  }
  return fields;
}

function computeBacklinks(notes: readonly Note[], byId: ReadonlyMap<string, Note>): Record<string, Backlink[]> {
  const collected = new Map<string, Map<string, Backlink>>();
  const add = (target: unknown, type: string, source: string) => {
    if (typeof target !== "string" || !byId.has(target)) return;
    const bucket = collected.get(target) ?? new Map<string, Backlink>();
    bucket.set(`${type}\u0000${source}`, { type, source });
    collected.set(target, bucket);
  };

  for (const note of notes) {
    const a = note.attributes;
    for (const relation of list(a.relations)) {
      const { type, target } = record(relation);
      const inverse = typeof type === "string" ? RELATION_INVERSES[type] : undefined;
      if (inverse !== undefined) add(target, inverse, note.id);
    }
    for (const [field, inverse] of FIELD_INVERSES) {
      const value = a[field];
      for (const target of Array.isArray(value) ? value : [value]) add(target, inverse, note.id);
    }
  }

  const result: Record<string, Backlink[]> = {};
  for (const target of [...collected.keys()].sort(compareCodePoints)) {
    result[target] = [...collected.get(target)!.values()].sort(
      (x, y) => compareCodePoints(x.type, y.type) || compareCodePoints(x.source, y.source),
    );
  }
  return result;
}

function titleOf(value: unknown, byId: ReadonlyMap<string, Note>): string {
  const id = String(value);
  const title = byId.get(id)?.attributes.title;
  return typeof title === "string" ? title : id;
}

/** Collapse every line break (and the spaces around it) into one space, then trim. */
function oneLine(value: string): string {
  return value.replace(/[ \t]*(?:\r\n|\r|\n)[ \t]*/g, " ").trim();
}

function isScalar(value: unknown): value is string | number | boolean {
  return typeof value === "string" || typeof value === "number" || typeof value === "boolean";
}

function text(value: unknown): string {
  return value === undefined || value === null ? "" : String(value);
}

function list(value: unknown): unknown[] {
  return Array.isArray(value) ? value : [];
}

function record(value: unknown): Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : {};
}
