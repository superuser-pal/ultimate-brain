import { appendFile, stat, writeFile } from "node:fs/promises";

import { ensureDirectory, resolveWritableTarget } from "./fs-safe.ts";
import { formatTimestamp } from "./time.ts";

export const LOG_HEADER = "<!-- GENERATED by brain. Append-only. -->";

export interface LogEntry {
  op: string;
  /** Note id, or `-` when the operation has no single note. */
  id: string;
  title: string;
  pairs?: ReadonlyArray<readonly [key: string, value: string | number]>;
}

/** Format one log line (spec/cli.md §3.9). Always a single line: CR and LF are escaped. */
export function formatLogLine(now: Date, entry: LogEntry): string {
  const pairs = (entry.pairs ?? []).map(([key, value]) => ` ${key}=${quoteIfNeeded(String(value))}`).join("");
  return `- ${formatTimestamp(now)} ${entry.op} ${entry.id} ${quote(entry.title)}${pairs}`;
}

/**
 * Append lines to `log/<YYYY-MM>.md` (month of `now`). The file is created exclusively with
 * its header, then lines are appended, so concurrent writers never overwrite each other and an
 * unreadable log is an error, never a reason to start over. Returns the relative path.
 */
export async function appendLog(root: string, now: Date, entries: readonly LogEntry[]): Promise<string> {
  const path = `log/${formatTimestamp(now).slice(0, 7)}.md`;
  await ensureDirectory(root, "log");
  const { target } = await resolveWritableTarget(root, path);

  try {
    await writeFile(target, `${LOG_HEADER}\n\n`, { flag: "wx" });
  } catch (error) {
    if (!isNodeError(error) || error.code !== "EEXIST") throw error;
    if ((await stat(target)).size === 0) await appendFile(target, `${LOG_HEADER}\n\n`);
  }

  await appendFile(target, entries.map((entry) => `${formatLogLine(now, entry)}\n`).join(""));
  return path;
}

export interface ParsedLogLine {
  timestamp: string;
  op: string;
  id: string;
  title: string;
  pairs: Record<string, string>;
}

/** Read one line written by formatLogLine (spec/cli.md §3.9); null for anything else. */
export function parseLogLine(line: string): ParsedLogLine | null {
  const head = /^- (\S+) ([a-z][a-z0-9-]*) (\S+) /.exec(line);
  if (head === null) return null;
  let position = head[0].length;
  const title = readQuoted(line, position);
  if (title === null) return null;
  position = title.end;
  const pairs: Record<string, string> = {};
  while (position < line.length) {
    const key = /^ ([^\s=]+)=/.exec(line.slice(position));
    if (key === null) return null;
    position += key[0].length;
    if (line[position] === '"') {
      const value = readQuoted(line, position);
      if (value === null) return null;
      pairs[key[1]!] = value.text;
      position = value.end;
    } else {
      const end = line.indexOf(" ", position);
      pairs[key[1]!] = line.slice(position, end === -1 ? line.length : end);
      position = end === -1 ? line.length : end;
    }
  }
  return { timestamp: head[1]!, op: head[2]!, id: head[3]!, title: title.text, pairs };
}

function readQuoted(line: string, start: number): { text: string; end: number } | null {
  if (line[start] !== '"') return null;
  let text = "";
  for (let index = start + 1; index < line.length; index += 1) {
    const char = line[index]!;
    if (char === '"') return { text, end: index + 1 };
    if (char === "\\") {
      const next = line[index + 1];
      text += next === "n" ? "\n" : next === "r" ? "\r" : (next ?? "");
      index += 1;
    } else text += char;
  }
  return null;
}

function quote(value: string): string {
  const escaped = value
    .replaceAll("\\", "\\\\")
    .replaceAll('"', '\\"')
    .replaceAll("\r", "\\r")
    .replaceAll("\n", "\\n");
  return `"${escaped}"`;
}

function quoteIfNeeded(value: string): string {
  return /[\s"\\]/.test(value) || value === "" ? quote(value) : value;
}

function isNodeError(error: unknown): error is NodeJS.ErrnoException {
  return error instanceof Error && "code" in error;
}
