import { readFile } from "node:fs/promises";
import { join } from "node:path";

import { atomicWriteFile, ensureDirectory } from "./fs-safe.ts";
import { formatTimestamp } from "./time.ts";

export const LOG_HEADER = "<!-- GENERATED by brain. Append-only. -->";

export interface LogEntry {
  op: string;
  /** Note id, or `-` when the operation has no single note. */
  id: string;
  title: string;
  pairs?: ReadonlyArray<readonly [key: string, value: string | number]>;
}

/** Format one log line (spec/cli.md §3.9). */
export function formatLogLine(now: Date, entry: LogEntry): string {
  const pairs = (entry.pairs ?? []).map(([key, value]) => ` ${key}=${quoteIfNeeded(String(value))}`).join("");
  return `- ${formatTimestamp(now)} ${entry.op} ${entry.id} ${quote(entry.title)}${pairs}`;
}

/** Append lines to `log/<YYYY-MM>.md` (month of `now`), creating it with its header. Returns the relative path. */
export async function appendLog(root: string, now: Date, entries: readonly LogEntry[]): Promise<string> {
  const path = `log/${formatTimestamp(now).slice(0, 7)}.md`;
  await ensureDirectory(root, "log");

  let existing: string;
  try {
    existing = await readFile(join(root, path), "utf8");
  } catch {
    existing = `${LOG_HEADER}\n\n`;
  }
  if (!existing.endsWith("\n")) existing += "\n";

  const lines = entries.map((entry) => `${formatLogLine(now, entry)}\n`).join("");
  await atomicWriteFile(root, path, existing + lines);
  return path;
}

function quote(value: string): string {
  return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

function quoteIfNeeded(value: string): string {
  return /[\s"\\]/.test(value) || value === "" ? quote(value) : value;
}
