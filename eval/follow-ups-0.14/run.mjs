#!/usr/bin/env node
// CC-198 acceptance (decision 0079 §4; spec/capture-and-review.md §4.1, §6.3; cli §5.14.5, §5.14.6, §5.22).
// Walks brain-ingest's references/selection.md step by step with the CLI on a synthetic sandbox brain, and writes what each
// step ran and returned to runs/steps.md. Notion is simulated: a Task page "created" is a made-up page id. Synthetic data only.
//
//   npm run build                      once (the sandbox runs bin/brain.js)
//   node eval/follow-ups-0.14/run.mjs  exit 0 when every check passes
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { chmodSync, cpSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const HERE = import.meta.dirname;
const REPO = join(HERE, "..", "..");
const FIX = join(REPO, "tests", "fixtures", "minutes-0079");
const LEAN = readFileSync(join(FIX, "lean-summary.md"), "utf8");
const INLINE = readFileSync(join(FIX, "inline-summary.md"), "utf8");
const TRANSCRIPT = readFileSync(join(FIX, "transcript.md"), "utf8");
const LEAN_PAGE = "0a0b0c0d-1e2f-4a3b-8c4d-5e6f7a8b9c0d";
const INLINE_PAGE = "0a0b0c0d-1e2f-4a3b-8c4d-5e6f7a8b9c0e";
const FRESH_PAGE = "0a0b0c0d-1e2f-4a3b-8c4d-5e6f7a8b9c0f";
const PROJECT = "prj-9x4t1b7e";
const NOW = "2027-03-10T09:00:00Z";

// ---- The sandbox: the fixture brain with the vendored skills, a failing gh, a Git repo ----
const SANDBOX = mkdtempSync(join(tmpdir(), "ub-follow-ups-"));
const BRAIN = join(SANDBOX, "brain");
const WORK = join(SANDBOX, "work");
const BIN = join(SANDBOX, "bin");
cpSync(join(REPO, "tests", "fixtures", "brain-acme"), BRAIN, { recursive: true });
for (const target of [".agents/skills", ".claude/skills"]) {
  rmSync(join(BRAIN, target), { recursive: true, force: true });
  cpSync(join(REPO, ".agents", "skills"), join(BRAIN, target), { recursive: true });
}
cpSync(join(REPO, "templates", "brain", "AGENTS.md"), join(BRAIN, "AGENTS.md"));
mkdirSync(WORK);
mkdirSync(BIN);
writeFileSync(join(BIN, "gh"), "#!/bin/sh\necho 'gh: not available in this sandbox' >&2\nexit 1\n");
chmodSync(join(BIN, "gh"), 0o755);
const ENV = { ...process.env, PATH: `${BIN}:${process.env.PATH}`, BRAIN_DIR: BRAIN, GIT_AUTHOR_NAME: "Sandbox", GIT_AUTHOR_EMAIL: "sandbox@sandbox.example", GIT_COMMITTER_NAME: "Sandbox", GIT_COMMITTER_EMAIL: "sandbox@sandbox.example" };
const git = (...args) => execFileSync("git", args, { cwd: BRAIN, env: ENV, encoding: "utf8" });
git("init", "-q");
git("add", "-A");
git("commit", "-q", "--allow-empty", "-m", "fixture");

// ---- The trace ----
const lines = [];
const say = (text = "") => lines.push(text);
const checks = [];
const check = (name, fn) => {
  try {
    fn();
    checks.push([name, "pass"]);
  } catch (error) {
    checks.push([name, `FAIL: ${error.message.split("\n")[0]}`]);
  }
};
const file = (name, value) => {
  const path = join(WORK, name);
  writeFileSync(path, typeof value === "string" ? value : JSON.stringify(value, null, 2));
  return path;
};
function brain(args, show = (data) => data) {
  const run = spawnSync("node", [join(REPO, "bin", "brain.js"), ...args, "--brain", BRAIN, "--json"], { env: ENV, encoding: "utf8" });
  const shown = args.map((arg) => (arg.startsWith(WORK) ? `<${arg.slice(WORK.length + 1)}>` : arg)).join(" ");
  let json;
  try {
    json = JSON.parse(run.stdout);
  } catch {
    throw new Error(`brain ${shown}: exit ${run.status}: ${run.stdout}${run.stderr}`);
  }
  say(`$ brain ${shown}  →  exit ${run.status}`);
  say("```json");
  say(JSON.stringify(json.ok === false ? json.error : show(json.data), null, 1));
  say("```");
  return { code: run.status, json };
}
let pageCounter = 0;
const notionCreate = (payload) => `7e5a0000-0000-4000-8000-${String(++pageCounter).padStart(12, "0")}`;
const planView = (data) => ({
  ok: data.ok, shape: data.shape, write_required: data.write_required, problems: data.problems,
  selection: data.selection.map((entry) => `${entry.id}: ${entry.effective}`),
  passages: data.passages.map((entry) => `¶${entry.n} ← ${entry.items.join(", ")}`),
  items: data.items?.map((item) => `${item.id} [${item.place}] ${item.track ? "Track · " : ""}${item.text}`),
  quick: data.quick, scopes: data.scopes, previous: data.previous,
});
const sourcesOf = (page) => readdirSync(join(BRAIN, "sources"), { recursive: true })
  .filter((name) => name.endsWith(".md"))
  .filter((name) => {
    const text = readFileSync(join(BRAIN, "sources", name), "utf8");
    return text.includes(`notion:${page}`) || text.includes(`extract_of: ${page}`);
  });

say("# CC-198 acceptance trace: lean minutes and follow-up Tasks");
say();
say(`Generated by \`eval/follow-ups-0.14/run.mjs\`. Sandbox: the synthetic \`brain-acme\` fixture with this branch's vendored skills, a \`gh\` that always fails, Notion simulated (a created Task is a made-up page id). Each step names the line of brain-ingest's \`references/selection.md\` (fork PR) it follows.`);

// ======================= Scenario 1: lean minutes, first read =======================
say();
say("## 1. Lean minutes, first read (the user ticked q2 and marked the page Reviewed)");
say();
say("**§2 step 2, first read?** An administrative lookup of sources whose `source_key` or `extract_of` names the page:");
say("```");
say(`grep → ${JSON.stringify(sourcesOf(LEAN_PAGE))}`);
say("```");
say("None: no `--previous`.");
say();
say("**§2 step 3, plan.** The summary file holds the For the brain toggle and the boxes as they are:");
const SUMMARY = file("lean-summary.md", LEAN);
const TRANS = file("transcript.md", TRANSCRIPT);
const plan1 = brain(["source", "extract-plan", "--page", LEAN_PAGE, "--summary", SUMMARY, "--transcript", TRANS], planView).json.data;
check("1a. the shape is lean and nothing blocks", () => { assert.equal(plan1.shape, "lean"); assert.equal(plan1.ok, true); });
check("1b. the selection is the toggle's: s2 and s4 Meeting only, s4.i2 Use in brain", () => {
  const eff = Object.fromEntries(plan1.selection.map((entry) => [entry.id, entry.effective]));
  assert.equal(eff.s2, "meeting only"); assert.equal(eff.s4, "meeting only"); assert.equal(eff["s4.i2"], "use"); assert.equal(eff.s1, "use"); assert.equal(eff.s3, "use");
});
const followUps1 = plan1.quick.filter((entry) => entry.task);
check("1c. the unticked follow-ups q1 and q3 are task: true; ticked q2 is not", () => {
  assert.deepEqual(plan1.quick.map((entry) => [entry.follow_up, entry.done, entry.task]), [["q1", false, true], ["q2", true, false], ["q3", false, true]]);
});
say();
say(`**§4, preview** (what the attended run shows; not a CLI call): ${followUps1.length} quick follow-ups become Tasks: ${followUps1.map((entry) => entry.text).join("; ")}. To keep one out, tick or delete it on the page. Then the user's yes, and the page read again after it: unchanged, so the run writes.`);
say();
say("**§4, write the extract:**");
const extract1 = brain(["source", "extract", "--page", LEAN_PAGE, "--title", "Community garden call", "--date", "2027-03-10", "--summary", SUMMARY, "--transcript", TRANS, "--now", NOW]).json.data;
const SRC1 = extract1.created[0];
const body1 = readFileSync(join(BRAIN, extract1.path), "utf8");
check("1d. the extract holds the selected paragraphs only: no excluded paragraph, no follow-up text", () => {
  assert.ok(!body1.includes("twelve hundred"), "s2's paragraph (Meeting only) stays out");
  assert.ok(!body1.includes("wedding"), "s4.i1's paragraph (Meeting only) stays out");
  assert.ok(body1.includes("herb spiral"), "s4.i2 (Use in brain) enters");
  assert.ok(!body1.includes("supplier's phone number") && !body1.includes("shed key") && !body1.includes("call notes"), "no follow-up text in Git");
});
say();
say("**SKILL.md step 7, the meeting note** (the analysis itself is not part of this check; the meeting is written so its Tasks can be recorded on it):");
const MTG = brain(["id", "new", "meeting"]).json.data.ids[0];
const noted = brain(["note", "new", "--input", file("notes.json", { notes: [{ type: "meeting", id: MTG, title: "Community garden call", frontmatter: { summary: "The planting day moves to April.", date: "2027-03-10", attendees: [], source: SRC1, projects: [PROJECT], sources: [SRC1], notion: LEAN_PAGE }, body: `## Summary\nThe planting day moves to the second Saturday of April. ^[${SRC1}#¶2:${plan1.passages.find((entry) => entry.n === 2).hash}]\n` }] })], (data) => ({ created: data.created?.map((entry) => entry.id ?? entry), skipped: data.skipped }));
git("add", "-A");
git("commit", "-q", "--allow-empty", "-m", "ingest: Community garden call 2027-03-10");
check("1g. the meeting note is written", () => assert.equal(noted.code, 0));
say();
say("**§6, Tasks** (in the publish's Tasks step): the owner's items s1.i3 (its Scope's due) and s3.i2, and each `quick` entry with `task: true` as `{ title, follow_up, projects }`. s1.i4 carries `Track: Waiting On —`: a Waiting On Task; this fixture maps no owner property, so the title keeps the line's `Waiting on Ben:` start, as §6 says.");
const items1 = [
  { title: "Draft the volunteer rota for planting day", item: "s1.i3", projects: [PROJECT], due: plan1.scopes.find((scope) => scope.item === "s1.i3").due },
  { title: "Email the council about the tap repair warranty", item: "s3.i2", projects: [PROJECT] },
  { title: plan1.items.find((item) => item.id === "s1.i4").text, status: "waiting_on", owner: "Ben", item: "s1.i4", projects: [PROJECT] },
  ...followUps1.map((entry) => ({ title: entry.text, follow_up: entry.follow_up, projects: [PROJECT] })),
];
const tasks1 = brain(["sync", "tasks", "--source", SRC1, "--input", file("tasks-1.json", { items: items1 })], (data) => data.items.map((item) => ({ item: item.item, follow_up: item.follow_up, title: item.properties.Name.value, due: item.properties.Due?.value ?? null }))).json.data.items;
check("1e. one Task payload per unticked follow-up, with no due date and no item", () => {
  const fu = tasks1.filter((item) => item.follow_up);
  assert.deepEqual(fu.map((item) => item.follow_up), ["q1", "q3"]);
  for (const item of fu) { assert.equal(item.properties.Due, undefined); assert.equal(item.item, undefined); }
});
const created1 = tasks1.map((item) => ({ key: item.follow_up ?? item.item, page: notionCreate(item) }));
say();
say(`Simulated Notion: ${created1.length} Task pages created (${created1.map((entry) => `${entry.key} → ${entry.page}`).join(", ")}).`);
say();
say("**§6, record:** on the extract, `tasks` and `task_items` (item ids and `q` ids); on the meeting, `tasks`.");
const fuPages1 = created1.filter((entry) => /^q\d+$/.test(entry.key)).map((entry) => entry.page);
const recorded1 = brain(["sync", "record", "--input", file("record-1.json", { records: [
  { id: SRC1, synced_at: NOW, tasks: created1.map((entry) => entry.page), task_items: Object.fromEntries(created1.map((entry) => [entry.key, entry.page])) },
  { id: MTG, synced_at: NOW, tasks: created1.map((entry) => entry.page) },
] })]);
git("add", "-A");
git("commit", "-q", "--allow-empty", "-m", "publish: Community garden call 2027-03-10");
check("1h. both records (the extract and the meeting) are recorded", () => assert.deepEqual(recorded1.json.data.records.map((record) => record.result), ["recorded", "recorded"]));
check("1f. the extract's frontmatter holds the q keys and nothing of their text", () => {
  const text = readFileSync(join(BRAIN, "sources", sourcesOf(LEAN_PAGE)[0]), "utf8");
  assert.match(text, /q1: 7e5a/); assert.match(text, /q3: 7e5a/);
  assert.ok(!text.includes("supplier's phone number") && !text.includes("shed key"));
});
say();
say(`Report's Done line: "5 tasks created (2 from quick follow-ups)". Check: nothing held back (q2 was ticked, so it is not a held-back follow-up).`);

// ======================= Scenario 2: the same page read again =======================
say();
say("## 2. The same page set back to Reviewed, unchanged: a second read");
say();
say(`**§2 step 2:** the lookup finds ${JSON.stringify(sourcesOf(LEAN_PAGE))}: the latest, \`--previous ${SRC1}\`.`);
const plan2 = brain(["source", "extract-plan", "--page", LEAN_PAGE, "--summary", SUMMARY, "--transcript", TRANS, "--previous", SRC1], planView).json.data;
check("2a. UNCHANGED, and no follow-up is task: true; q1 and q3 name their Tasks", () => {
  assert.equal(plan2.write_required, false);
  assert.deepEqual(plan2.quick.map((entry) => [entry.follow_up, entry.task, entry.recorded]), [["q1", false, fuPages1[0]], ["q2", false, null], ["q3", false, fuPages1[1]]]);
});
say();
say("**§6:** no `quick` entry has `task: true`, and every item id is in `task_items`: no Task. The CLI's own guard, had a session sent q1 anyway:");
const refused = brain(["sync", "tasks", "--source", SRC1, "--input", file("tasks-2.json", { items: [{ title: "Send Ben the supplier's phone number", follow_up: "q1", projects: [PROJECT] }] })]);
check("2b. sync tasks refuses q1 a second time, naming its page", () => {
  assert.equal(refused.json.error.code, "INPUT_INVALID");
  assert.match(refused.json.error.message, new RegExp(fuPages1[0]));
});
check("2c. a second read creates no Task", () => assert.equal(plan2.quick.filter((entry) => entry.task).length, 0));
say();
say(`Report: no Tasks on the Done line; under Check, "Community garden call: q1 and q3 are already Tasks" (held back as \`recorded\`).`);

// ======================= Scenario 3: the user unticks q2 and asks for a read =======================
say();
say("## 3. The user unticks q2 and sets the page back to Reviewed");
say();
const SUMMARY3 = file("lean-summary-3.md", LEAN.replace("- [x] Share the call notes with Carla [q2]", "- [ ] Share the call notes with Carla [q2]"));
const plan3 = brain(["source", "extract-plan", "--page", LEAN_PAGE, "--summary", SUMMARY3, "--transcript", TRANS, "--previous", SRC1], planView).json.data;
check("3a. only q2 becomes a Task at this read; q1 and q3 stay recorded", () => {
  assert.deepEqual(plan3.quick.map((entry) => [entry.follow_up, entry.task]), [["q1", false], ["q2", true], ["q3", false]]);
});
const tasks3 = brain(["sync", "tasks", "--source", SRC1, "--input", file("tasks-3.json", { items: plan3.quick.filter((entry) => entry.task).map((entry) => ({ title: entry.text, follow_up: entry.follow_up, projects: [PROJECT] })) })], (data) => data.items.map((item) => ({ follow_up: item.follow_up, title: item.properties.Name.value }))).json.data.items;
check("3b. one payload, for q2", () => assert.deepEqual(tasks3.map((item) => item.follow_up), ["q2"]));

// ======================= Scenario 4: an inline-quote meeting =======================
say();
say("## 4. A meeting in the inline-quote shape (the 0.9.x prompt), with a `[q1]` on a quick follow-up");
say();
const SUMMARY4 = file("inline-summary.md", INLINE);
const plan4 = brain(["source", "extract-plan", "--page", INLINE_PAGE, "--summary", SUMMARY4, "--transcript", TRANS], planView).json.data;
check("4a. not lean: no shape, and no quick entry has follow_up or task", () => {
  assert.equal(plan4.shape, undefined);
  assert.equal(plan4.ok, true);
  for (const entry of plan4.quick) { assert.equal(entry.follow_up, undefined); assert.equal(entry.task, undefined); }
});
check("4b. so the skill creates no follow-up Task: zero items with task: true", () => assert.equal(plan4.quick.filter((entry) => entry.task === true).length, 0));
say();
say("**§6:** \"In the inline-quote shape no follow-up ever becomes a Task\": its quick lines stay in Notion; only its numbered owner items can become Tasks.");

// ======================= Scenario 5: the toggle as Notion's Markdown gives it =======================
say();
say("## 5. The For the brain toggle as the page's Markdown gives it, and with its tags dropped");
say();
say("A page not read before. Notion returns a toggle's lines indented by a tab. §2 step 1 keeps the toggle whole (tags, lines, indentation); notion.md's source-body rule 3 (drop `<details>` and its indentation) is for a summary stored whole and never applies to it.");
const toggleStart = LEAN.indexOf("<details>\n<summary>For the brain</summary>");
const indented = LEAN.slice(0, toggleStart) + LEAN.slice(toggleStart).split("\n").map((line) => (line === "" || /^<\/?(details|summary)/.test(line) ? line : `\t${line}`)).join("\n");
const plan5 = brain(["source", "extract-plan", "--page", FRESH_PAGE, "--summary", file("lean-indented.md", indented), "--transcript", TRANS], (data) => ({ ok: data.ok, shape: data.shape, problems: data.problems, quick: data.quick.map((entry) => [entry.follow_up, entry.task]) })).json.data;
check("5a. the toggle kept whole, its lines tab-indented, plans as the fixture does", () => {
  assert.equal(plan5.ok, true); assert.equal(plan5.shape, "lean");
  assert.deepEqual(plan5.passages, plan1.passages);
  assert.deepEqual(plan5.quick.map((entry) => entry.task), plan1.quick.map((entry) => entry.task));
});
const stripped = indented.replace(/<\/?(details|summary)>/g, "").replaceAll("\t", "");
const plan5b = brain(["source", "extract-plan", "--page", FRESH_PAGE, "--summary", file("lean-stripped.md", stripped), "--transcript", TRANS], (data) => ({ ok: data.ok, shape: data.shape, problems: data.problems.slice(0, 3) })).json.data;
check("5b. with the toggle's tags dropped, the plan blocks (SELECTION_UNREADABLE): nothing may be written", () => {
  assert.equal(plan5b.ok, false);
  assert.ok(plan5b.problems.some((problem) => problem.code === "SELECTION_UNREADABLE"));
});

// ======================= Summary =======================
say();
say("## Checks");
say();
say("| Check | Result |");
say("|---|---|");
for (const [name, result] of checks) say(`| ${name} | ${result} |`);
mkdirSync(join(HERE, "runs"), { recursive: true });
const trace = lines.join("\n").replaceAll(SANDBOX, "<sandbox>");
writeFileSync(join(HERE, "runs", "steps.md"), `${trace}\n`);
rmSync(SANDBOX, { recursive: true, force: true });
const failed = checks.filter(([, result]) => result !== "pass");
console.log(`${checks.length - failed.length}/${checks.length} checks pass${failed.length ? `; failed: ${failed.map(([name]) => name).join("; ")}` : ""}`);
process.exit(failed.length ? 1 : 0);
