import assert from "node:assert/strict";
import { mkdir, mkdtemp, readdir, readFile, realpath, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test, type TestContext } from "node:test";

import { brain } from "./helpers.ts";

async function scratch(context: TestContext): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), "brain-init-"));
  context.after(() => rm(root, { recursive: true, force: true }));
  return root;
}

test("init creates a valid empty brain with an index and append-only init log", async (context) => {
  const root = await scratch(context);
  const target = join(root, "new-brain");
  const init = await brain([
    "init", target, "--owner", "Test Owner", "--no-git", "--now", "2026-12-03T10:22:00Z", "--json",
  ], root);

  assert.equal(init.code, 0, init.stderr);
  assert.equal(init.json.ok, true);
  assert.equal(init.json.brain, await realpath(target));
  assert.equal(init.json.data.path_abs, await realpath(target));
  assert.equal(init.json.data.git.initialized, false);
  assert.equal(init.json.data.git.committed, false);
  assert.equal(init.json.data.created.includes("brain.json"), true);
  assert.equal(init.json.data.created.includes("knowledge/people/.gitkeep"), true);
  assert.equal(await readFile(join(target, "brain.json"), "utf8").then(JSON.parse).then((value) => value.owner.name), "Test Owner");
  assert.equal(
    await readFile(join(target, "log", "2026-12.md"), "utf8"),
    '<!-- GENERATED by brain. Append-only. -->\n\n- 2026-12-03T10:22:00Z init - "Test Owner" schema=1\n',
  );

  const lint = await brain(["lint", "--brain", target, "--json"], root);
  assert.equal(lint.code, 0, lint.stdout);
  assert.equal(lint.json.data.errors, 0);

  const status = await brain(["status", "--brain", target, "--json"], root);
  assert.deepEqual(status.json.data.notes, {
    area: 0, project: 0, person: 0, org: 0, meeting: 0, decision: 0,
    question: 0, concept: 0, source: 0, view: 0, goal: 0, memory: 0,
  });
  assert.equal(status.json.data.index_stale, false);
  assert.equal(status.json.data.last_log, '- 2026-12-03T10:22:00Z init - "Test Owner" schema=1');
});

test("init refuses unsafe targets and --force preserves pre-existing template files", async (context) => {
  const root = await scratch(context);
  const target = join(root, "existing");
  await mkdir(target);
  await writeFile(join(target, "README.md"), "keep me\n");

  const refused = await brain(["init", target, "--no-git", "--json"], root);
  assert.equal(refused.code, 5);
  assert.equal(refused.json.error.code, "TARGET_NOT_EMPTY");

  await writeFile(join(target, ".gitignore"), "custom\n");
  const forced = await brain(["init", target, "--force", "--owner", "Owner", "--no-git", "--json"], root);
  assert.equal(forced.code, 0, forced.stdout);
  assert.equal(forced.json.data.skipped.includes(".gitignore"), true);
  assert.equal(await readFile(join(target, ".gitignore"), "utf8"), "custom\n");
  assert.equal(await readFile(join(target, "README.md"), "utf8"), "keep me\n");

  const already = await brain(["init", target, "--force", "--no-git", "--json"], root);
  assert.equal(already.code, 5);
  assert.equal(already.json.error.code, "ALREADY_A_BRAIN");
});

test("config validates changes, status reports Notion configuration, and id new checks types", async (context) => {
  const root = await scratch(context);
  const target = join(root, "brain");
  await brain(["init", target, "--no-git", "--json"], root);

  const set = await brain([
    "config", "set", "notion.databases.projects", '"2c4e6a80-1b3d-4f50-9a7c-8e6d4b2a0f13"', "--brain", target, "--json",
  ], root);
  assert.equal(set.code, 0, set.stdout);
  assert.equal(set.json.data.previous, "");
  const get = await brain(["config", "get", "notion.databases.projects", "--brain", target, "--json"], root);
  assert.deepEqual(get.json.data, { path: "notion.databases.projects", value: "2c4e6a80-1b3d-4f50-9a7c-8e6d4b2a0f13" });

  const schemaVersion = await brain(["config", "set", "schema_version", "1", "--brain", target, "--json"], root);
  assert.equal(schemaVersion.code, 4);
  assert.equal(schemaVersion.json.error.code, "INPUT_INVALID");
  const invalid = await brain(["config", "set", "notion.databases.projects", "42", "--brain", target, "--json"], root);
  assert.equal(invalid.code, 4);
  assert.equal(invalid.json.error.code, "INPUT_INVALID");

  const status = await brain(["status", "--brain", target, "--json"], root);
  assert.deepEqual(status.json.data.notion.configured, ["projects"]);
  assert.equal(status.json.data.notion.tasks_database, false);

  const ids = await brain(["id", "new", "decision", "--count", "2", "--brain", target, "--json"], root);
  assert.equal(ids.code, 0, ids.stdout);
  assert.equal(ids.json.data.ids.length, 2);
  assert.equal(new Set(ids.json.data.ids).size, 2);
  assert.equal(ids.json.data.ids.every((id: string) => /^dec-[0-9abcdefghjkmnpqrstvwxyz]{8}$/.test(id)), true);
  const badType = await brain(["id", "new", "unknown", "--brain", target, "--json"], root);
  assert.equal(badType.code, 2);
});

test("init can record the new default brain without inspecting the product repository", async (context) => {
  const root = await scratch(context);
  const home = join(root, "home");
  const target = join(root, "brain");
  await mkdir(home);
  const init = await brain(["init", target, "--no-git", "--set-default", "--json"], home);
  assert.equal(init.code, 0, init.stderr);
  assert.deepEqual(
    JSON.parse(await readFile(join(home, ".config", "ultimate-brain", "config.json"), "utf8")),
    { brain: await realpath(target) },
  );
  assert.equal(init.json.data.default_config.written, true);
});

test("init installs every shipped skill and --force leaves existing skill files alone", async (context) => {
  const root = await scratch(context);
  const target = join(root, "skills-brain");
  const names = (await readdir(join(import.meta.dirname, "..", "skills"), { withFileTypes: true }))
    .filter((entry) => entry.isDirectory()).map((entry) => entry.name);
  assert.ok(names.length >= 6);

  const init = await brain(["init", target, "--owner", "Test Owner", "--no-git", "--json"], root);
  assert.equal(init.code, 0, init.stderr);
  for (const name of names) {
    assert.ok(init.json.data.created.includes(`.agents/skills/${name}/SKILL.md`), name);
    assert.equal(
      await readFile(join(target, ".agents", "skills", name, "SKILL.md"), "utf8"),
      await readFile(join(import.meta.dirname, "..", ".agents", "skills", name, "SKILL.md"), "utf8"),
    );
  }

  const other = join(root, "forced");
  await mkdir(join(other, ".agents", "skills", "brain-query"), { recursive: true });
  await writeFile(join(other, ".agents", "skills", "brain-query", "SKILL.md"), "mine\n");
  const forced = await brain(["init", other, "--owner", "Test Owner", "--no-git", "--force", "--json"], root);
  assert.equal(forced.code, 0, forced.stderr);
  assert.ok(forced.json.data.skipped.includes(".agents/skills/brain-query/SKILL.md"));
  assert.equal(await readFile(join(other, ".agents", "skills", "brain-query", "SKILL.md"), "utf8"), "mine\n");
});
