import assert from "node:assert/strict";
import { readFile, rm } from "node:fs/promises";
import { join } from "node:path";
import { test } from "node:test";

import { formatLogLine } from "../src/lib/log.ts";
import { brain, fixtureCopy } from "./helpers.ts";

test("log lines escape titles and quote values with spaces", () => {
  const line = formatLogLine(new Date("2026-12-03T10:22:00.000Z"), {
    op: "ingest",
    id: "mtg-8c4n2p7w",
    title: 'Say "hi" \\ bye',
    pairs: [["created", 4], ["note", "two words"]],
  });
  assert.equal(line, '- 2026-12-03T10:22:00Z ingest mtg-8c4n2p7w "Say \\"hi\\" \\\\ bye" created=4 note="two words"');
});

test("brain log appends to the month file and defaults the title to the note's", async (context) => {
  const dir = await fixtureCopy(context);
  const before = await readFile(join(dir, "log/2026-12.md"), "utf8");

  const run = await brain([
    "log", "ingest", "mtg-8c4n2p7w", "created=4", "proposals=3",
    "--brain", dir, "--now", "2026-12-06T09:00:00Z", "--json",
  ]);
  assert.equal(run.code, 0, run.stdout);
  assert.equal(run.json.data.path, "log/2026-12.md");
  const line = '- 2026-12-06T09:00:00Z ingest mtg-8c4n2p7w "Acme sync" created=4 proposals=3';
  assert.equal(run.json.data.line, line);
  assert.equal(await readFile(join(dir, "log/2026-12.md"), "utf8"), `${before}${line}\n`);
});

test("brain log creates a new month file with its header", async (context) => {
  const dir = await fixtureCopy(context);
  await rm(join(dir, "log"), { recursive: true });

  const run = await brain(["log", "publish", "-", "--title", "nightly", "--brain", dir, "--now", "2027-01-02T03:04:05Z", "--json"]);
  assert.equal(run.code, 0, run.stdout);
  assert.equal(
    await readFile(join(dir, "log/2027-01.md"), "utf8"),
    '<!-- GENERATED by brain. Append-only. -->\n\n- 2027-01-02T03:04:05Z publish - "nightly"\n',
  );
});

test("brain log rejects bad ops, unknown ids and a bad --now", async (context) => {
  const dir = await fixtureCopy(context);
  assert.equal((await brain(["log", "Bad_Op", "--brain", dir, "--json"])).json.error.code, "USAGE");

  const unknown = await brain(["log", "ingest", "mtg-00000000", "--brain", dir, "--json"]);
  assert.equal(unknown.code, 4);
  assert.equal(unknown.json.error.code, "UNKNOWN_ID");

  const now = await brain(["log", "ingest", "--now", "yesterday", "--brain", dir, "--json"]);
  assert.equal(now.code, 2);
});
