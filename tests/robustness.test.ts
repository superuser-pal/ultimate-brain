test("argument errors: extra positionals, single-dash tokens, bad keys, empty --brain", async () => {
  const usage = async (args: string[]) => (await brain([...args, "--json"])).json.error.code;
  assert.equal(await usage(["index", "extra", "--brain", FIXTURE_BRAIN]), "USAGE");
  assert.equal(await usage(["index", "-x", "--brain", FIXTURE_BRAIN]), "USAGE");
  assert.equal(await usage(["log", "ingest", "Bad-Key=1", "--brain", FIXTURE_BRAIN]), "USAGE");
  assert.equal(await usage(["index", "--brain="]), "USAGE");

  const afterSeparator = await brain(["log", "--brain", FIXTURE_BRAIN, "--", "--json"]);
  assert.equal(afterSeparator.json, undefined, "--json after -- is not an option");
});

