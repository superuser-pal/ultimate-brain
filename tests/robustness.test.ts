function note(id: string, type: string, attributes: Record<string, unknown>): Note {
  return { id, type, path: `knowledge/x/${id}.md`, body: "", raw: "", attributes: { id, type, ...attributes } };
}

test("index values never break lines; titles escape backslashes; odd types are left out", () => {
  const { markdown } = buildIndex([
    note("con-00000001", "concept", { title: "Path C:\\dir\\\nnext", summary: "line one  \r\n  line two\r", aliases: ["a\nb", { bad: 1 }] }),
    note("per-00000001", "person", { title: "P", summary: "s", org: ["org-1", "org-2"], facts: { role: { nested: true } } }),
  ]);
  const lines = markdown.trimEnd().split("\n");
  assert.ok(lines.includes("- [Path C:\\\\dir\\\\ next](knowledge/x/con-00000001.md) — con-00000001 · line one line two · aliases: a b"));
  assert.ok(lines.includes("- [P](knowledge/x/per-00000001.md) — per-00000001 · s"));
});

test("reference lists render every title; backlinks skip missing ids and notes without links", () => {
  const built = buildIndex([
    note("prj-00000001", "project", { title: "One", summary: "s" }),
    note("prj-00000002", "project", { title: "Two", summary: "s" }),
    note("dec-00000001", "decision", { title: "D", summary: "s", date: "2026-01-01", assessment: "accepted", projects: ["prj-00000001", "prj-00000002", "prj-missing01"] }),
  ]);
  assert.match(built.markdown, /project: One, Two, prj-missing01 · s/);
  assert.deepEqual(Object.keys(built.backlinks), ["prj-00000001", "prj-00000002"]);
  assert.equal(built.backlinks["dec-00000001"], undefined);
});

