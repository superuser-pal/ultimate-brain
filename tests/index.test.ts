import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { test } from "node:test";

import { buildIndex } from "../src/lib/index-builder.ts";
import type { Note } from "../src/lib/notes.ts";
import { brain, fixtureCopy, FIXTURE_BRAIN } from "./helpers.ts";

test("the fixture brain's index.md is exactly what brain index produces", async () => {
  const run = await brain(["index", "--check", "--brain", FIXTURE_BRAIN, "--json"]);
  assert.equal(run.code, 0, run.stdout);
  assert.equal(run.json.ok, true);
  assert.equal(run.json.data.stale, false);
  assert.equal(run.json.data.written, false);
});

test("brain index rewrites a stale index and is byte-stable on re-run", async (context) => {
  const dir = await fixtureCopy(context);
  const expected = await readFile(join(dir, "index.md"), "utf8");
  await writeFile(join(dir, "index.md"), "stale\n");

  const check = await brain(["index", "--check", "--brain", dir, "--json"]);
  assert.equal(check.code, 1);
  assert.equal(check.json.data.stale, true);
  assert.equal(await readFile(join(dir, "index.md"), "utf8"), "stale\n", "--check writes nothing");

  const first = await brain(["index", "--brain", dir, "--json"]);
  assert.equal(first.code, 0);
  assert.equal(first.json.data.written, true);
  assert.equal(await readFile(join(dir, "index.md"), "utf8"), expected);

  const second = await brain(["index", "--brain", dir, "--json"]);
  assert.equal(second.json.data.written, false);
  assert.equal(await readFile(join(dir, "index.md"), "utf8"), expected);
});

test("brain index --json lists every note and computed backlinks", async () => {
  const run = await brain(["index", "--check", "--brain", FIXTURE_BRAIN, "--json"]);
  const { notes, backlinks, counts } = run.json.data;

  assert.equal(notes.length, 22);
  assert.deepEqual(counts, {
    area: 1, goal: 1, project: 1, person: 2, org: 1, meeting: 2, decision: 2,
    question: 1, concept: 1, reference: 0, source: 2, view: 3, proposal: 4, memory: 1,
  });
  assert.deepEqual(notes.map((note: { path: string }) => note.path), [...notes.map((note: { path: string }) => note.path)].sort());

  const project = notes.find((note: { id: string }) => note.id === "prj-9x4t1b7e");
  assert.deepEqual(project.fields, { status: "Active", client: "org-6d1f9z3k", goal: "gol-4p9r2w6t" });
  assert.equal(project.lifecycle, "reviewed");
  const source = notes.find((note: { id: string }) => note.id === "src-7w3c9k5m");
  assert.equal(source.lifecycle, null);
  assert.equal(source.summary, null);

  assert.deepEqual(backlinks["mtg-8c4n2p7w"], [
    { type: "decisions", source: "dec-7k2m9q4x" },
    { type: "questions", source: "que-8n3v5x1d" },
  ]);
  assert.deepEqual(backlinks["per-9t2c6m4a"], [
    { type: "attended", source: "mtg-5r2k8v3a" },
    { type: "attended", source: "mtg-8c4n2p7w" },
    { type: "mentioned_in", source: "que-8n3v5x1d" },
  ]);
  assert.deepEqual(backlinks["con-1s6t8e2b"], [{ type: "related_to", source: "dec-7k2m9q4x" }]);
  assert.deepEqual(backlinks["gol-4p9r2w6t"], [{ type: "goal_of", source: "prj-9x4t1b7e" }]);
  // The persisted supersession pair is not a computed backlink.
  assert.equal(
    (backlinks["dec-2p9f6h1r"] ?? []).some((link: { type: string }) => link.type.startsWith("supersed")),
    false,
  );
  assert.deepEqual(Object.keys(backlinks), [...Object.keys(backlinks)].sort());
});

function note(id: string, type: string, attributes: Record<string, unknown>, path = `knowledge/x/${id}.md`): Note {
  return { id, type, path, body: "", raw: "", attributes: { id, type, ...attributes } };
}

test("index lines sort by NFC-lowercased code points, escape brackets and flag lifecycle", () => {
  const { markdown } = buildIndex([
    note("con-00000001", "concept", { title: "abeja", summary: "b" }),
    note("con-00000002", "concept", { title: "Ábaco", summary: "a\nsecond line", lifecycle: "disputed" }),
    note("con-00000003", "concept", { title: "[draft] Zeta", summary: "z", aliases: ["Z", "zz"], lifecycle: "draft" }),
  ]);
  assert.equal(
    markdown,
    [
      "<!-- GENERATED by brain index. Do not edit. -->",
      "",
      "# Index",
      "",
      "## Concepts",
      "- [\\[draft\\] Zeta](knowledge/x/con-00000003.md) — con-00000003 · z · aliases: Z, zz",
      "- [abeja](knowledge/x/con-00000001.md) — con-00000001 · b",
      "- [Ábaco](knowledge/x/con-00000002.md) — con-00000002 · a second line · disputed",
      "",
    ].join("\n"),
  );
});

test("references render titles, falling back to the id when the note is missing", () => {
  const { markdown } = buildIndex([
    note("per-00000001", "person", { title: "Ana", summary: "s", org: "org-missing01", facts: { role: "CTO" } }),
  ]);
  assert.match(markdown, /— per-00000001 · org: org-missing01 · role: CTO · s$/m);
});

test("an empty brain gets the bare index header", () => {
  assert.equal(buildIndex([]).markdown, "<!-- GENERATED by brain index. Do not edit. -->\n\n# Index\n");
});

test("index warns on unparseable notes and duplicate ids instead of failing", async (context) => {
  const dir = await fixtureCopy(context);
  await mkdir(join(dir, "knowledge", "concepts"), { recursive: true });
  await writeFile(join(dir, "knowledge/concepts/broken.md"), "---\ntitle: [unclosed\n---\n");
  const original = await readFile(join(dir, "knowledge/concepts/row-level-security.md"), "utf8");
  await writeFile(join(dir, "knowledge/concepts/zz-copy.md"), original);

  const run = await brain(["index", "--brain", dir, "--json"]);
  assert.equal(run.code, 0);
  const codes = run.json.warnings.map((warning: { code: string }) => warning.code).sort();
  assert.deepEqual(codes, ["DUPLICATE_ID", "UNPARSEABLE"]);
});

test("brain resolution errors use contract codes and exit 3", async (context) => {
  const dir = await fixtureCopy(context);
  const missing = await brain(["index", "--json"]);
  assert.equal(missing.code, 3);
  assert.equal(missing.json.error.code, "BRAIN_NOT_CONFIGURED");

  const notABrain = await brain(["index", "--brain", join(dir, "areas"), "--json"]);
  assert.equal(notABrain.code, 3);
  assert.equal(notABrain.json.error.code, "BRAIN_NOT_FOUND");

  await writeFile(join(dir, "brain.json"), JSON.stringify({ schema_version: 2 }));
  const version = await brain(["index", "--brain", dir, "--json"]);
  assert.equal(version.json.error.code, "SCHEMA_VERSION_UNSUPPORTED");
});

test("unknown options are usage errors (exit 2)", async () => {
  const run = await brain(["index", "--bogus", "--brain", FIXTURE_BRAIN, "--json"]);
  assert.equal(run.code, 2);
  assert.equal(run.json.error.code, "USAGE");
});
